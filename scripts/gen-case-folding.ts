// `pnpm gen:case-folding <CaseFolding.txt>`: writes shared/src/case-folding.ts, the Unicode
// default full case folding table (statuses C and F) that the bot name key uses
// (domain-model.md §2 Name key; M2 plan P3). No library: the table is pinned to the Unicode
// version of Node's ICU, which the NFKC steps of the name key use too.
//
// Download the file of that version first, for example
// https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt for `process.versions.unicode`
// 17.0. A test fails when Node's Unicode version and the table's differ; regenerate then, and
// recompute the stored `bots.name_key` values in a migration (M2 plan §8).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const OUTPUT = "shared/src/case-folding.ts";

const file = process.argv[2];
if (file === undefined) {
  console.error("Usage: pnpm gen:case-folding <path to CaseFolding.txt>");
  process.exit(2);
}
const text = readFileSync(file, "utf8");
const version = /CaseFolding-([\d.]+)\.txt/.exec(text)?.[1];
if (version === undefined) {
  console.error(`${file} has no "CaseFolding-<version>.txt" header line`);
  process.exit(2);
}
const sha = createHash("sha256").update(text).digest("hex");

const entries: string[] = [];
for (const line of text.split("\n")) {
  const body = line.split("#")[0]?.trim() ?? "";
  if (body === "") continue;
  const [code = "", status = "", mapping = ""] = body.split(";").map((part) => part.trim());
  if (status !== "C" && status !== "F") continue;
  entries.push(`${code}:${mapping.replaceAll(" ", ".")}`);
}

// Lines of at most about 96 characters, so the file stays readable in a diff.
const chunks: string[] = [];
let line = "";
for (const entry of entries) {
  if (line.length + entry.length + 1 > 96) {
    chunks.push(line);
    line = "";
  }
  line += `${line === "" ? "" : ","}${entry}`;
}
if (line !== "") chunks.push(line);

writeFileSync(
  OUTPUT,
  `// Generated by \`pnpm gen:case-folding\` (scripts/gen-case-folding.ts) from Unicode
// CaseFolding-${version}.txt, sha256 ${sha}.
// Statuses C and F: Unicode default full case folding. Do not edit by hand.
export const CASE_FOLDING_UNICODE_VERSION = "${version}";

// "<code point>:<code point>[.<code point>…]" in hex, comma-separated.
const DATA = [
${chunks.map((chunk) => `  "${chunk}",`).join("\n")}
].join(",");

export const CASE_FOLDING: ReadonlyMap<number, string> = new Map(
  DATA.split(",").map((entry) => {
    const [from = "", to = ""] = entry.split(":");
    return [
      Number.parseInt(from, 16),
      String.fromCodePoint(...to.split(".").map((hex) => Number.parseInt(hex, 16))),
    ];
  }),
);
`,
);
console.log(`${OUTPUT}: ${String(entries.length)} entries from Unicode ${version}`);
